def M(t):
    """map original-time seconds -> edited-time seconds"""
    acc = 0.0
    for a, b in keep:
        if t < a:
            return round(acc, 3)  # inside a removed gap -> next segment start
        if t <= b:
            return round(acc + (t - a), 3)
        acc += b - a
    return round(acc, 3)

